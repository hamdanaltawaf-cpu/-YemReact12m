// ============================================================
// التطبيع العربي للبحث (Arabic Normalization)
// ============================================================
// يوازي النص العربي لتوحيد الاختلافات الشائعة قبل المقارنة:
// إزالة التشكيل، توحيد الألفات (أ إ آ ا)، ي/ى، ة/ه، التطويل، علامات الترقيم.

export function normalizeArabic(text) {
  if (!text) return '';
  return String(text)
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '')   // إزالة التشكيل والحركات
    .replace(/[\u0640]/g, '')                              // إزالة التطويل (ــ)
    .replace(/[أإآ]/g, 'ا')                                // توحيد الألفات
    .replace(/ى/g, 'ي')                                    // توحيد الألف المقصورة مع الياء
    .replace(/ة/g, 'ه')                                    // توحيد التاء المربوطة مع الهاء
    .replace(/[\u200B-\u200F\uFEFF]/g, '')                 // إزالة محارف العرض صفرية
    .replace(/[.,;:!?؟،؛\-_'"()[\]{}/\\|«»…]/g, ' ')       // علامات الترقيم → مسافة
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

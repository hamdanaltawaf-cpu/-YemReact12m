-- يخزّن النص المعيَّر عربيًا (إزالة تشكيل وتوحيد حروف) ليُستخدم في البحث
-- بالموقف بموثوقية، بعيدًا عن اختلاف التشكيل/الألف/الياء.

ALTER TABLE reactions ADD COLUMN IF NOT EXISTS search_text TEXT;

-- فهرس GIN للنص المطبّع (يدعم بحث التجزئة لاحقًا)
CREATE INDEX IF NOT EXISTS idx_reactions_search_text ON reactions (search_text);
